# 2. TRANSFORMATION LAYER (Meta-Schema Parsing & Feature Extraction)
# =====================================================================
def transform_dashboard_telemetry(df):
    """
    Parses nested JSON layout payloads generated by the AI model.
    Extracts structural design telemetry to evaluate generation quality.
    """
    print("[Transformation] Flattening dynamic JSON schemas and calculating layout complexity...")
    
    df['timestamp'] = pd.to_datetime(df['timestamp'])
    
    # Lists to capture dynamically extracted configurations
    widget_counts = []
    ui_themes = []
    layout_types = []
    
    # Iterate through row records and extract properties safely from the AI's design schema
    for _, row in df.iterrows():
        try:
            layout_meta = json.loads(row['generated_layout'])
            widget_counts.append(len(layout_meta.get('widgets', [])))
            ui_themes.append(layout_meta.get('theme', 'unknown'))
            layout_types.append(layout_meta.get('grid_type', 'fluid'))
        except (json.JSONDecodeError, TypeError):
            widget_counts.append(0)
            ui_themes.append('malformed')
            layout_types.append('unknown')
            
    # Assign newly structured metrics back to core DataFrame
    df['total_widgets_rendered'] = widget_counts
    df['ui_theme_selected'] = ui_themes
    df['layout_grid_type'] = layout_types
    
    # Derive an abstract generation efficiency index: query time cost per layout widget
    df['latency_per_widget_ms'] = df['query_execution_ms'] / df['total_widgets_rendered']
    
    return df

