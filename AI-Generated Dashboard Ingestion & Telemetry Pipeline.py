# 3. MODERN META-ANALYTICS VISUALIZATION
# =====================================================================
def render_meta_analytics_dashboard(df):
    """
    Renders an executive operational dashboard visualizing the health, 
    complexity, and user acceptance of AI-generated user interfaces.
    """
    print("[Visualization] Instantiating AI-Generated Dashboard Performance Cockpit...")
    
    # Create subplots matrix
    fig = make_subplots(
        rows=2, cols=2,
        subplot_titles=(
            'Dashboard Generation Latency vs. Layout Complexity',
            'User Satisfaction (CSAT) by Interface Theme',
            'Distribution of Automated Grid Layout Frameworks',
            'AI Ingestion Health Matrix'
        ),
        specs=[[{"type": "xy"}, {"type": "xy"}],
               [{"type": "bar"}, {"type": "domain"}]]
    )

    # Plot 1: Latency vs Complexity (Top Left)
    fig.add_trace(
        go.Scatter(
            x=df['total_widgets_rendered'],
            y=df['query_execution_ms'],
            mode='markers+text',
            text=df['dashboard_id'],
            textposition="top left",
            marker=dict(size=15, color='#00CC96', line=dict(width=1.5, color='white')),
            name="Dashboards"
        ),
        row=1, col=1
    )
    fig.update_xaxes(title_text="Number of Rendered Widgets", row=1, col=1)
    fig.update_yaxes(title_text="Warehouse Query Latency (ms)", row=1, col=1)

    # Plot 2: CSAT by UI Theme (Top Right)
    theme_perf = df.groupby('ui_theme_selected')['user_rating_score'].mean().reset_index()
    fig.add_trace(
        go.Bar(
            x=theme_perf['ui_theme_selected'],
            y=theme_perf['user_rating_score'],
            marker_color=['#AB63FA', '#636EFA'],
            name="Avg Score"
        ),
        row=1, col=2
    )
    fig.update_yaxes(title_text="Average Score (1-5)", row=1, col=2)

    # Plot 3: Grid System Selection Mix (Bottom Left)
    grid_counts = df['layout_grid_type'].value_counts().reset_index()
    fig.add_trace(
        go.Bar(
            x=grid_counts['layout_grid_type'],
            y=grid_counts['count'],
            marker_color='#19D3BF',
            name="Layout Count"
        ),
        row=2, col=1
    )
    fig.update_yaxes(title_text="Generation Volume", row=2, col=1)

    # Plot 4: Operational Metrics Card (Bottom Right)
    avg_render_latency = df['query_execution_ms'].mean()
    fig.add_trace(
        go.Indicator(
            mode="number",
            value=avg_render_latency,
            number={'suffix': " ms", 'valueformat': ".0f"},
            title={"text": "Average AI SQL Execution Overhead"}
        ),
        row=2, col=2
    )

    # Unified Layout Stylings
    fig.update_layout(
        title_text="Autonomous UI Factory: Dynamic Dashboard Telemetry Analytics",
        template="plotly_dark",
        showlegend=False,
        height=850,
        width=1200
    )
    
    fig.show()

